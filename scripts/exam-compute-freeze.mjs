#!/usr/bin/env node
// Content freeze for the two expensive exam seed sweeps.
//
// audit-sentence-exams.mjs and audit-word-exams.mjs are ~20 of the ~24 minutes
// the core-release gate spends. Both are pure deterministic computation over a
// fixed set of repository files: identical input bytes produce an identical
// verdict. So when those bytes are unchanged since the last verified run, the
// sweep cannot reach a different answer and re-running it buys nothing.
//
// This tool pins a SHA-256 per input file. The gate consults it only when asked
// with --respect-freeze, which CI passes on pull requests and deliberately does
// NOT pass on push:main — main and releases always re-run both sweeps in full,
// so no merged commit is ever certified by a skipped audit.
//
// The input set is CAPTURED, not hand-written. A hand-maintained path list is
// precisely how a gate silently stops covering a dependency, so --write runs
// each audit with fs reads instrumented and records what it actually opened,
// then unions that with a static scan of the audit source as a backstop.
//
//   node scripts/exam-compute-freeze.mjs --write            # (re)pin the manifest
//   node scripts/exam-compute-freeze.mjs --check            # frozen? exit 0 : 1
//   node scripts/exam-compute-freeze.mjs --check sentence-exams
//   node scripts/exam-compute-freeze.mjs --status           # human summary
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { tmpdir } from "node:os";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST_PATH = join(ROOT, "docs", "generated", "exam_compute_freeze.json");
const SCHEMA_VERSION = 1;

// Pinning runs each audit with the SAME arguments the gate uses — no reduced
// seed counts. A pin has to mean "these exact bytes were verified in full",
// otherwise --respect-freeze would let an unverified state skip forever. This
// makes --write slow (~20 min) on purpose; it is a rare operation.
const AUDITS = [
  { key: "sentence-exams", script: "scripts/audit-sentence-exams.mjs", captureArgs: [] },
  { key: "word-exams", script: "scripts/audit-word-exams.mjs", captureArgs: [] },
];

function sha256(relPath) {
  return createHash("sha256").update(readFileSync(join(ROOT, relPath))).digest("hex");
}

// Backstop for inputs behind a branch the capture run did not take: any
// repo-relative file path spelled literally in the audit source.
function staticallyReferencedFiles(scriptRel) {
  const source = readFileSync(join(ROOT, scriptRel), "utf8");
  const found = new Set();
  for (const match of source.matchAll(/["'`]([\w./-]+\.(?:js|mjs|json))["'`]/g)) {
    const candidate = match[1].replace(/^\.\//, "");
    if (candidate.startsWith("node:")) continue;
    for (const prefix of ["", "docs/generated/", "docs/authoring/", "docs/reviews/", "scripts/", "scripts/lib/"]) {
      const rel = prefix + candidate;
      if (existsSync(join(ROOT, rel))) found.add(rel);
    }
  }
  return found;
}

function captureInputs(audit) {
  const outPath = join(tmpdir(), `hanapath-freeze-${audit.key}-${process.pid}.json`);
  const result = spawnSync(
    process.execPath,
    ["scripts/lib/capture-audit-reads.mjs", audit.script, outPath, ...audit.captureArgs],
    { cwd: ROOT, stdio: ["ignore", "inherit", "inherit"] },
  );
  // Refuse to pin a state the audit did not certify. Without this a red sweep
  // could be frozen and then skipped indefinitely on every pull request.
  if (result.status !== 0) {
    console.error(`\n  ${audit.key} did not pass; refusing to pin (exit ${result.status}).`);
    return null;
  }
  if (!existsSync(outPath)) {
    console.error(`\n  capture produced no read set for ${audit.key}; refusing to pin.`);
    return null;
  }
  const observed = new Set(JSON.parse(readFileSync(outPath, "utf8")));
  for (const rel of staticallyReferencedFiles(audit.script)) observed.add(rel);
  observed.add(audit.script);
  return [...observed].sort();
}

function writeManifest() {
  const audits = {};
  for (const audit of AUDITS) {
    console.log(`\n=== pinning ${audit.key} (full run, this is slow by design) ===`);
    const files = captureInputs(audit);
    if (!files) return 1;
    const hashes = {};
    for (const rel of files) hashes[rel] = sha256(rel);
    audits[audit.key] = { script: audit.script, inputCount: files.length, inputs: hashes };
    console.log(`${files.length} inputs`);
  }
  const manifest = {
    schemaVersion: SCHEMA_VERSION,
    note:
      "Generated by scripts/exam-compute-freeze.mjs --write. Each hash pins one input of an "
      + "exam seed sweep. The gate skips a sweep only when every hash still matches AND only "
      + "when invoked with --respect-freeze (pull requests). push:main always runs both in full.",
    audits,
  };
  mkdirSync(dirname(MANIFEST_PATH), { recursive: true });
  writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`Wrote ${MANIFEST_PATH}`);
  return 0;
}

// Pure comparison, split out so the regression test can exercise the
// changed/missing paths without mutating tracked files. `hashOf` returns null
// when the input no longer exists.
export function diffPinnedInputs(inputs, hashOf) {
  const changed = [];
  for (const [rel, pinned] of Object.entries(inputs)) {
    const actual = hashOf(rel);
    if (actual === null || actual === undefined) changed.push(`${rel} (missing)`);
    else if (actual !== pinned) changed.push(rel);
  }
  return changed;
}

// Returns {frozen, reason, changed[]} — frozen only when every pinned input is
// byte-identical. Anything unexpected (missing manifest, missing file, new
// schema) reports not-frozen so the gate falls back to running the sweep.
export function checkFreeze(key) {
  if (!existsSync(MANIFEST_PATH)) return { frozen: false, reason: "no freeze manifest", changed: [] };
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
  } catch {
    return { frozen: false, reason: "freeze manifest is unreadable", changed: [] };
  }
  if (manifest.schemaVersion !== SCHEMA_VERSION) {
    return { frozen: false, reason: `freeze manifest schema ${manifest.schemaVersion} != ${SCHEMA_VERSION}`, changed: [] };
  }
  const entry = manifest.audits?.[key];
  if (!entry?.inputs) return { frozen: false, reason: `${key} is not pinned`, changed: [] };

  const changed = diffPinnedInputs(entry.inputs, (rel) =>
    (existsSync(join(ROOT, rel)) ? sha256(rel) : null));
  return changed.length
    ? { frozen: false, reason: `${changed.length} input(s) changed`, changed }
    : { frozen: true, reason: `${Object.keys(entry.inputs).length} inputs unchanged`, changed: [] };
}

export { AUDITS, MANIFEST_PATH };

function main() {
  const args = process.argv.slice(2);
  if (args.includes("--write")) process.exit(writeManifest());

  const wantsCheck = args.includes("--check");
  const wantsStatus = args.includes("--status");
  if (!wantsCheck && !wantsStatus) {
    console.error("usage: exam-compute-freeze.mjs --write | --check [key] | --status");
    process.exit(2);
  }

  const explicit = args.find((a) => !a.startsWith("--"));
  const keys = explicit ? [explicit] : AUDITS.map((a) => a.key);
  let allFrozen = true;
  for (const key of keys) {
    const result = checkFreeze(key);
    if (!result.frozen) allFrozen = false;
    console.log(`  ${key}: ${result.frozen ? "FROZEN" : "CHANGED"} — ${result.reason}`);
    for (const rel of result.changed.slice(0, 8)) console.log(`      ${rel}`);
    if (result.changed.length > 8) console.log(`      ... and ${result.changed.length - 8} more`);
  }
  if (wantsStatus) process.exit(0);
  process.exit(allFrozen ? 0 : 1);
}

// Only run when invoked directly, not when the gate imports checkFreeze.
if (pathToFileURL(process.argv[1] || "").href === import.meta.url) {
  main();
}
